// entityShape merges a resource's read.json and list.json shapes: read has
// more fields, list more samples for optionality.
func (g *generator) entityShape(res []string) (Shape, bool) {
	base := "/api/v1/" + strings.Join(res, "/")
	var shapes []Shape
	for _, p := range []string{base + "/read.json", base + "/list.json"} {
		r, ok := g.probed.ok(p)
		if !ok {
			continue
		}
		s := r.Shape
		if s.Kind == "array" && s.Items != nil {
			s = *s.Items
		}
		if s.Kind == "object" {
			shapes = append(shapes, s)
		}
	}
	if len(shapes) == 0 {
		return Shape{}, false
	}
	out := shapes[0]
	for _, s := range shapes[1:] {
		out = mergeShapes(out, s)
	}
	return out, true
}

func mergeShapes(a, b Shape) Shape {
	if a.Kind == "unknown" {
		return b
	}
	if b.Kind == "unknown" {
		return a
	}
	if a.Kind == "array" && b.Kind == "array" {
		items := mergeShapes(*a.Items, *b.Items)
		return Shape{Kind: "array", Items: &items}
	}
	if a.Kind != "object" || b.Kind != "object" {
		return a
	}
	out := Shape{Kind: "object"}
	for _, fa := range a.Fields {
		if fb, ok := b.field(fa.Name); ok {
			out.Fields = append(out.Fields, ShapeField{Name: fa.Name, Shape: mergeShapes(fa.Shape, fb.Shape), Optional: fa.Optional || fb.Optional})
		} else {
			out.Fields = append(out.Fields, ShapeField{Name: fa.Name, Shape: fa.Shape, Optional: true})
		}
	}
	for _, fb := range b.Fields {
		if _, ok := a.field(fb.Name); !ok {
			out.Fields = append(out.Fields, ShapeField{Name: fb.Name, Shape: fb.Shape, Optional: true})
		}
	}
	return out
}

func writableParams(eps []Endpoint) map[string]Param {
	out := map[string]Param{}
	for _, e := range eps {
		if !strings.HasSuffix(e.Path, "/create.json") && !strings.HasSuffix(e.Path, "/update.json") {
			continue
		}
		for _, p := range e.Params {
			if _, ok := out[p.Name]; !ok {
				out[p.Name] = p
			}
		}
	}
	return out
}

func paramIndex(ps []Param) map[string]Param {
	out := map[string]Param{}
	for _, p := range ps {
		if _, ok := out[p.Name]; !ok {
			out[p.Name] = p
		}
	}
	return out
}

func docScalar(p Param) string {
	switch p.Type {
	case "NUMBER":
		return "number"
	case "BOOLEAN":
		return "boolean"
	case "TEXT", "DATE", "HTML", "XML", "CSV":
		return "string"
	}
	return ""
}

// widenNullFields types a field that was null in every sample from the
// documented create/update parameter of the same name.
func widenNullFields(s Shape, documented map[string]Param) Shape {
	if s.Kind == "array" && s.Items != nil {
		items := widenNullFields(*s.Items, documented)
		return Shape{Kind: "array", Items: &items}
	}
	if s.Kind != "object" {
		return s
	}
	out := Shape{Kind: "object"}
	for _, f := range s.Fields {
		p, has := documented[f.Name]
		next := f.Shape
		if next.Kind == "scalar" && len(next.Types) == 1 && next.Types[0] == "null" {
			if sc := docScalar(p); has && sc != "" {
				next = Shape{Kind: "scalar", Types: []string{sc, "null"}}
			}
		} else if next.Kind == "object" || next.Kind == "array" {
			next = widenNullFields(next, paramIndex(p.Fields))
		}
		out.Fields = append(out.Fields, ShapeField{Name: f.Name, Shape: next, Optional: f.Optional})
	}
	return out
}

// foldSelfReferences makes a tree node's children the node's own type where
// a nested array's element fields are a subset of the parent's.
func foldSelfReferences(s Shape) Shape {
	if s.Kind != "object" {
		return s
	}
	parent := map[string]bool{}
	for _, f := range s.Fields {
		parent[f.Name] = true
	}
	merged := s
	folded := map[string]bool{}
	for _, f := range s.Fields {
		if f.Shape.Kind != "array" || f.Shape.Items == nil || f.Shape.Items.Kind != "object" {
			continue
		}
		child := f.Shape.Items.Fields
		if len(child) < 3 {
			continue
		}
		subset := true
		for _, c := range child {
			if !parent[c.Name] {
				subset = false
				break
			}
		}
		if subset {
			merged = mergeShapes(merged, *f.Shape.Items)
			folded[f.Name] = true
		}
	}
	if len(folded) == 0 {
		return s
	}
	out := Shape{Kind: "object"}
	for _, f := range merged.Fields {
		if folded[f.Name] {
			f.Shape = Shape{Kind: "array", Items: &Shape{Kind: "self"}}
		}
		out.Fields = append(out.Fields, f)
	}
	return out
}

const selfToken = "\x00self\x00"

// shapeGo renders a probed shape as a Go type, declaring the structs it
// needs in the group's file. fieldName types ids as int64.
func (g *generator) shapeGo(s Shape, hint, self, grp, fieldName string, entity bool) string {
	switch s.Kind {
	case "unknown":
		return "json.RawMessage"
	case "self":
		if self == "" {
			return "json.RawMessage"
		}
		return self
	case "scalar":
		var types []string
		null := false
		for _, t := range s.Types {
			if t == "null" {
				null = true
			} else {
				types = append(types, t)
			}
		}
		if len(types) != 1 {
			return "json.RawMessage"
		}
		var t string
		switch types[0] {
		case "string":
			t = "string"
		case "boolean":
			t = "bool"
		case "number":
			t = "float64"
			if idLike(fieldName) {
				t = "int64"
			} else if intLike(fieldName) {
				t = "int"
			}
		}
		if null {
			return "*" + t
		}
		return t
	case "array":
		if s.Items == nil {
			return "[]json.RawMessage"
		}
		return "[]" + g.shapeGo(*s.Items, singular(hint), self, grp, fieldName, false)
	case "object":
		folded := foldSelfReferences(s)
		if len(folded.Fields) == 0 {
			return "json.RawMessage"
		}
		var body strings.Builder
		seen := map[string]int{}
		for _, f := range folded.Fields {
			name := goName(f.Name)
			if seen[name]++; seen[name] > 1 {
				name += strconv.Itoa(seen[name])
			}
			t := g.shapeGo(f.Shape, hint+goName(f.Name), selfToken, grp, f.Name, false)
			if t == selfToken {
				t = "*" + t
			}
			fmt.Fprintf(&body, "\t%s %s `json:\"%s,omitempty\"`\n", name, t, f.Name)
		}
		return g.declareStruct(hint, body.String(), grp, entity)
	}
	return "json.RawMessage"
}

func (g *generator) declareStruct(hint, body, grp string, entity bool) string {
	candidates := []string{hint}
	if !entity {
		candidates = append(candidates, hint+"Field", hint+"Field2", hint+"Field3")
	}
	for _, name := range candidates {
		concrete := strings.ReplaceAll(body, selfToken, name)
		prev, taken := g.claimed[name]
		switch {
		case taken && prev == "\x00entity" && entity:
		case taken && prev == concrete:
			return name
		case taken:
			continue
		}
		g.claimed[name] = concrete
		g.structOf[name] = grp
		g.stats.Structs++
		out := g.group(grp)
		doc := name + " is a response object, typed from the shapes the TypeScript SDK's probe recorded."
		if entity {
			doc = name + " is a record of /api/v1/" + resourcePath(name, g) + ", typed from the shapes the TypeScript SDK's probe recorded."
		}
		out.entities.WriteString(comment(doc, ""))
		fmt.Fprintf(&out.entities, "type %s struct {\n%s}\n\n", name, concrete)
		return name
	}
	panic("no name for struct " + hint)
}

func resourcePath(entity string, g *generator) string {
	var found string
	var walk func(n *node)
	walk = func(n *node) {
		if len(n.segs) > 0 && typeName(n.segs) == entity {
			found = strings.Join(n.segs, "/")
		}
		for _, c := range n.children {
			walk(c)
		}
	}
	walk(g.root)
	return found
}

func (g *generator) envelopeKind(e Endpoint) string {
	if e.Method != "GET" {
		return ""
	}
	if p, ok := g.probed.ok(e.Path); ok && p.Envelope == "raw" {
		return ""
	}
	_, verb := splitPath(e.Path)
	switch verb {
	case "list.json", "tree.json":
		return "array"
	case "read.json":
		return "object"
	}
	return ""
}

func (g *generator) binary(e Endpoint) bool {
	if binaryPaths[e.Path] {
		return true
	}
	_, verb := splitPath(e.Path)
	if i := strings.LastIndex(verb, "."); i >= 0 {
		return binarySuffixes[verb[i+1:]]
	}
	return false
}

func (g *generator) resultName(e Endpoint) string {
	res, verb := splitPath(e.Path)
	return typeName(res) + methodName(verb) + "Result"
}

func (g *generator) isStruct(t string) bool {
	_, ok := g.structOf[t]
	return ok
}

func (g *generator) ptr(t string) string {
	if g.isStruct(t) {
		return "*" + t
	}
	return t
}

// returnType is the Go return type of an endpoint and how its answer is read:
// download, post, list, unwrap (the data member) or raw.
func (g *generator) returnType(e Endpoint, entity string) (string, string) {
	if g.binary(e) {
		return "*Download", "download"
	}
	if e.Method == "POST" {
		return "*WriteResult", "post"
	}
	_, verb := splitPath(e.Path)
	grp := strings.Split(strings.TrimPrefix(e.Path, "/api/v1/"), "/")[0]
	probe, probed := g.probed.ok(e.Path)
	switch g.envelopeKind(e) {
	case "array":
		if probed && probe.Shape.Kind == "array" && probe.Shape.Items != nil {
			items := *probe.Shape.Items
			// A tree node carries more than the entity (cls, leaf, children),
			// so only list.json answers the entity itself.
			if items.Kind == "object" && entity != "" && verb == "list.json" {
				return "*List[" + entity + "]", "list"
			}
			return "*List[" + g.shapeGo(items, g.resultName(e), "", grp, "", false) + "]", "list"
		}
		if entity != "" && verb == "list.json" {
			return "*List[" + entity + "]", "list"
		}
		return "*List[json.RawMessage]", "list"
	case "object":
		if entity != "" {
			return "*" + entity, "unwrap"
		}
		if probed && probe.Shape.Kind == "object" {
			return g.ptr(g.shapeGo(probe.Shape, g.resultName(e), "", grp, "", false)), "unwrap"
		}
		return "json.RawMessage", "unwrap"
	}
	if !probed {
		return "json.RawMessage", "raw"
	}
	call := "raw"
	if probe.Envelope == "data" {
		call = "unwrap"
	}
	switch probe.Shape.Kind {
	case "array":
		if probe.Shape.Items != nil && probe.Shape.Items.Kind == "object" && entity != "" && verb == "list.json" {
			return "[]" + entity, call
		}
		if probe.Shape.Items == nil {
			return "[]json.RawMessage", call
		}
		return "[]" + g.shapeGo(*probe.Shape.Items, g.resultName(e), "", grp, "", false), call
	case "object":
		if entity != "" && (verb == "read.json" || verb == "list.json") {
			return "*" + entity, call
		}
		return g.ptr(g.shapeGo(probe.Shape, g.resultName(e), "", grp, "", false)), call
	}
	t := g.shapeGo(probe.Shape, g.resultName(e), "", grp, "", false)
	return strings.TrimPrefix(t, "*"), call
}
