// Package gen writes the endpoint methods of package cashctrl from the
// TypeScript SDK's spec/api.json (requests) and spec/responses.json (probed
// response shapes). It mirrors that SDK's scripts/generate.ts, so the two
// SDKs agree on names, envelopes and types.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Stats counts what Generate wrote.
type Stats struct {
	Endpoints, Groups, Resources, TypedResponses, RawResponses, Enums, Structs int
}

// Generate reads specDir/api.json and specDir/responses.json and returns the
// generated files by name.
func Generate(specDir string) (map[string][]byte, Stats, error) {
	var spec Spec
	if err := readJSON(filepath.Join(specDir, "api.json"), &spec); err != nil {
		return nil, Stats{}, err
	}
	var probed ResponseSpec
	if err := readJSON(filepath.Join(specDir, "responses.json"), &probed); err != nil {
		return nil, Stats{}, err
	}
	applySpecCorrections(&spec)
	g := newGenerator(spec, probed)
	return g.run()
}

func readJSON(path string, out any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(b, out); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

type node struct {
	segs      []string
	children  []*node
	byName    map[string]*node
	endpoints []Endpoint
}

type groupOut struct {
	services, entities, params bytes.Buffer
}

type enumReq struct {
	values     []string
	candidates []string
	doc        string
	name       string
}

type generator struct {
	spec   Spec
	probed ResponseSpec
	root   *node

	claimed    map[string]string // identifier -> body for structs, "" for the rest
	structOf   map[string]string // struct name -> group whose file holds it
	groups     map[string]*groupOut
	groupOrder []string
	enums      []*enumReq
	enumByName map[string]*enumReq
	tests      bytes.Buffer
	stats      Stats
}

// core is what the hand-written files of package cashctrl declare.
var core = []string{
	"Client", "New", "Lang", "LangDE", "LangFR", "LangIT", "LangEN", "WithLang", "APIError", "FieldError", "DecodeError",
	"Download", "List", "WriteResult", "Date", "DateOf", "NewDate", "ParseDate", "Filter", "Where", "Comparison", "Eq",
	"Like", "Gt", "Lt", "SortDir", "Asc", "Desc", "Ptr", "All",
}

func newGenerator(spec Spec, probed ResponseSpec) *generator {
	g := &generator{spec: spec, probed: probed, root: &node{byName: map[string]*node{}},
		claimed: map[string]string{}, structOf: map[string]string{}, groups: map[string]*groupOut{},
		enumByName: map[string]*enumReq{}}
	for _, n := range core {
		g.claimed[n] = ""
	}
	for _, e := range spec.Endpoints {
		res, _ := splitPath(e.Path)
		n := g.root
		for _, s := range res {
			c, ok := n.byName[s]
			if !ok {
				c = &node{segs: append(append([]string{}, n.segs...), s), byName: map[string]*node{}}
				n.byName[s] = c
				n.children = append(n.children, c)
			}
			n = c
		}
		n.endpoints = append(n.endpoints, e)
	}
	return g
}

func (g *generator) group(name string) *groupOut {
	o, ok := g.groups[name]
	if !ok {
		o = &groupOut{}
		g.groups[name] = o
		g.groupOrder = append(g.groupOrder, name)
	}
	return o
}

func (g *generator) run() (map[string][]byte, Stats, error) {
	// Resource entity names go first, so a nested type that happens to be
	// spelled like a resource does not take its name.
	var claimEntities func(n *node)
	claimEntities = func(n *node) {
		if len(n.segs) > 0 {
			if _, ok := g.entityShape(n.segs); ok {
				if _, taken := g.claimed[typeName(n.segs)]; taken {
					panic("entity " + typeName(n.segs) + " collides with a hand-written name")
				}
				g.claimed[typeName(n.segs)] = "\x00entity"
			}
			g.claimed[typeName(n.segs)+"Service"] = ""
		}
		for _, c := range n.children {
			claimEntities(c)
		}
	}
	claimEntities(g.root)
	for _, c := range g.root.children {
		g.emitNode(c)
	}
	g.resolveEnums()

	files := map[string][]byte{}
	header := "// Code generated by cmd/gen from spec/api.json and spec/responses.json. DO NOT EDIT.\n\npackage cashctrl\n\n"
	for _, name := range g.groupOrder {
		o := g.groups[name]
		var b bytes.Buffer
		var body bytes.Buffer
		body.Write(o.services.Bytes())
		body.Write(o.params.Bytes())
		body.Write(o.entities.Bytes())
		b.WriteString(header)
		b.WriteString("import (\n")
		for _, imp := range []struct{ pkg, use string }{{"context", "context."}, {"encoding/json", "json."}, {"net/http", "http."}, {"net/url", "url."}} {
			if regexp.MustCompile(`\b` + regexp.QuoteMeta(imp.use) + `[A-Z]`).Match(body.Bytes()) {
				fmt.Fprintf(&b, "\t%q\n", imp.pkg)
			}
		}
		b.WriteString(")\n\n")
		b.Write(body.Bytes())
		src, err := g.finish(b.Bytes(), name+"_gen.go")
		if err != nil {
			return nil, g.stats, err
		}
		files[name+"_gen.go"] = src
	}

	var eb bytes.Buffer
	eb.WriteString(header)
	for _, e := range g.enums {
		if e.name == "" || g.enumByName[e.name] != e {
			continue
		}
		g.stats.Enums++
		eb.WriteString(comment(e.name+" is "+e.doc, ""))
		fmt.Fprintf(&eb, "type %s string\n\n// The values of %s.\nconst (\n", e.name, e.name)
		for _, v := range e.values {
			fmt.Fprintf(&eb, "\t%s %s = %q\n", g.enumConstName(e.name, v, e.values), e.name, v)
		}
		eb.WriteString(")\n\n")
	}
	src, err := g.finish(eb.Bytes(), "enums_gen.go")
	if err != nil {
		return nil, g.stats, err
	}
	files["enums_gen.go"] = src

	var tb bytes.Buffer
	tb.WriteString("// Code generated by cmd/gen from spec/api.json and spec/responses.json. DO NOT EDIT.\n\npackage cashctrl\n\n")
	tb.WriteString("import \"context\"\n\n")
	tb.WriteString("// generatedEndpoints calls every generated method once with empty params.\n")
	tb.WriteString("var generatedEndpoints = []genEndpoint{\n")
	tb.Write(g.tests.Bytes())
	tb.WriteString("}\n")
	src, err = g.finish(tb.Bytes(), "endpoints_gen_test.go")
	if err != nil {
		return nil, g.stats, err
	}
	files["endpoints_gen_test.go"] = src
	g.stats.Groups = len(g.groupOrder)
	return files, g.stats, nil
}

var enumToken = regexp.MustCompile("\x00enum([0-9]+)\x00")

func (g *generator) finish(src []byte, name string) ([]byte, error) {
	src = enumToken.ReplaceAllFunc(src, func(m []byte) []byte {
		i, _ := strconv.Atoi(string(m[5 : len(m)-1]))
		return []byte(g.enums[i].name)
	})
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("%s: %w\n%s", name, err, src)
	}
	return out, nil
}

// enumConstName keeps codes upper-case (DE, CHE) when every value of the
// enum is such a code, and pascal-cases the rest (NET, GROSS: Net, Gross).
func (g *generator) enumConstName(typ, v string, values []string) string {
	codes := true
	for _, x := range values {
		if !codeLike.MatchString(x) {
			codes = false
		}
	}
	if codes {
		return typ + v
	}
	return typ + goName(v)
}

var codeLike = regexp.MustCompile(`^[A-Z]{1,3}$`)

// resolveEnums names the enum types once every other name is claimed.
func (g *generator) resolveEnums() {
	for _, e := range g.enums {
		for _, c := range append(e.candidates, e.candidates[len(e.candidates)-1]+"Value") {
			if prev, ok := g.enumByName[c]; ok {
				if strings.Join(prev.values, "\x00") == strings.Join(e.values, "\x00") {
					e.name = c
					break
				}
				continue
			}
			if _, taken := g.claimed[c]; taken || g.constClash(c, e.values) {
				continue
			}
			g.claimed[c] = ""
			e.name = c
			g.enumByName[c] = e
			for _, v := range e.values {
				g.claimed[g.enumConstName(c, v, e.values)] = ""
			}
			break
		}
		if e.name == "" {
			panic("no name for enum " + e.candidates[0])
		}
	}
}

func (g *generator) constClash(typ string, values []string) bool {
	seen := map[string]bool{}
	for _, v := range values {
		n := g.enumConstName(typ, v, values)
		if _, taken := g.claimed[n]; taken || seen[n] {
			return true
		}
		seen[n] = true
	}
	return false
}

func (g *generator) enum(values []string, doc string, candidates ...string) string {
	for i, prev := range g.enums {
		if prev.candidates[0] == candidates[0] && strings.Join(prev.values, "\x00") == strings.Join(values, "\x00") {
			return fmt.Sprintf("\x00enum%d\x00", i)
		}
	}
	e := &enumReq{values: values, candidates: candidates, doc: doc}
	g.enums = append(g.enums, e)
	return fmt.Sprintf("\x00enum%d\x00", len(g.enums)-1)
}

/* ------------------------------------------------------------ resources -- */

func (g *generator) emitNode(n *node) {
	grp := n.segs[0]
	out := g.group(grp)
	tn := typeName(n.segs)
	svc := tn + "Service"
	g.stats.Resources++

	entity := ""
	if shape, ok := g.entityShape(n.segs); ok {
		widened := widenNullFields(shape, writableParams(n.endpoints))
		entity = g.shapeGo(widened, tn, "", grp, "", true)
	}

	fmt.Fprintf(&out.services, "// %s holds the endpoints under /api/v1/%s/.\ntype %s struct{ c *Client }\n\n",
		svc, strings.Join(n.segs, "/"), svc)
	last := n.segs[len(n.segs)-1]
	if len(n.segs) == 1 {
		fmt.Fprintf(&out.services, "// %s returns the endpoints under /api/v1/%s/.\nfunc (c *Client) %s() %s { return %s{c} }\n\n",
			goName(last), last, plainName(last), svc, svc)
	} else {
		parent := typeName(n.segs[:len(n.segs)-1]) + "Service"
		fmt.Fprintf(&out.services, "// %s returns the endpoints under /api/v1/%s/.\nfunc (s %s) %s() %s { return %s{s.c} }\n\n",
			plainName(last), strings.Join(n.segs, "/"), parent, plainName(last), svc, svc)
	}

	used := map[string]bool{}
	for _, c := range n.children {
		used[plainName(c.segs[len(c.segs)-1])] = true
	}
	for _, e := range n.endpoints {
		_, verb := splitPath(e.Path)
		name := methodName(verb)
		if used[name] {
			name += "Action"
		}
		used[name] = true
		g.emitMethod(out, n, svc, name, e, entity)
	}
	for _, c := range n.children {
		g.emitNode(c)
	}
}

func (g *generator) emitMethod(out *groupOut, n *node, svc, name string, e Endpoint, entity string) {
	g.stats.Endpoints++
	tn := typeName(n.segs)
	ep := strings.TrimPrefix(e.Path, "/api/v1/")
	paramsType := ""
	_, open := openParamEndpoints[e.Path]
	switch {
	case len(e.Params) > 0:
		paramsType = tn + name + "Params"
		g.emitParams(out, n, name, paramsType, e)
	case open:
		paramsType = "map[string]string"
	}

	rt, call := g.returnType(e, entity)
	if strings.HasPrefix(rt, "json.RawMessage") || rt == "*List[json.RawMessage]" {
		g.stats.RawResponses++
	} else if call != "post" && call != "download" {
		g.stats.TypedResponses++
	}

	var doc strings.Builder
	doc.WriteString(comment(fmt.Sprintf("%s calls %s /api/v1/%s: %s.", name, e.Method, ep, strings.TrimSuffix(e.Summary, ".")), ""))
	if e.Description != "" {
		doc.WriteString("//\n" + comment(e.Description, ""))
	}
	if rt == "json.RawMessage" || rt == "*List[json.RawMessage]" {
		doc.WriteString("//\n// The answer is not typed: the TypeScript SDK's probe recorded no shape for it.\n")
	}
	if open {
		doc.WriteString("//\n" + comment("The parameters are caller-chosen keys: "+openParamEndpoints[e.Path]+".", ""))
	}
	fmt.Fprintf(&doc, "//\n// See %s#%s\n", g.spec.Source, e.Anchor)
	out.services.WriteString(doc.String())

	sig := "ctx context.Context"
	switch {
	case paramsType == "map[string]string":
		sig += ", p map[string]string"
	case paramsType != "":
		sig += ", p *" + paramsType
	}
	retDecl := rt
	fmt.Fprintf(&out.services, "func (s %s) %s(%s) (%s, error) {\n", svc, name, sig, retDecl)
	var zero string
	switch {
	case strings.HasPrefix(rt, "*") || strings.HasPrefix(rt, "[]") || rt == "json.RawMessage":
		zero = "nil"
	case rt == "string":
		zero = `""`
	case rt == "bool":
		zero = "false"
	default:
		zero = "0"
	}
	switch {
	case paramsType == "map[string]string":
		out.services.WriteString("\tf := newForm()\n\tf.open(p)\n\tv, err := f.done()\n")
	case paramsType != "":
		out.services.WriteString("\tv, err := p.values()\n")
	default:
		out.services.WriteString("\tv, err := url.Values{}, error(nil)\n")
	}
	fmt.Fprintf(&out.services, "\tif err != nil {\n\t\treturn %s, err\n\t}\n", zero)
	method := "http.MethodGet"
	if e.Method == "POST" {
		method = "http.MethodPost"
	}
	switch call {
	case "download":
		fmt.Fprintf(&out.services, "\treturn download(ctx, s.c, %s, %q, v)\n", method, ep)
	case "post":
		fmt.Fprintf(&out.services, "\treturn post(ctx, s.c, %q, v)\n", ep)
	case "list":
		item := strings.TrimSuffix(strings.TrimPrefix(rt, "*List["), "]")
		fmt.Fprintf(&out.services, "\treturn getList[%s](ctx, s.c, %q, v)\n", item, ep)
	case "unwrap", "raw":
		fmt.Fprintf(&out.services, "\treturn getJSON[%s](ctx, s.c, %s, %q, v, %v)\n", rt, method, ep, call == "unwrap")
	}
	out.services.WriteString("}\n\n")

	// One call per method for the generated tests.
	arg := ""
	switch {
	case paramsType == "map[string]string":
		arg = ", map[string]string{}"
	case paramsType != "":
		arg = ", &" + paramsType + "{}"
	}
	chain := "c"
	for _, s := range n.segs {
		chain += "." + plainName(s) + "()"
	}
	probedKey := ""
	if _, ok := g.probed.ok(e.Path); ok {
		probedKey = e.Path
	}
	fmt.Fprintf(&g.tests, "\t{Method: %q, Path: %q, Call: %q, Probe: %q, Do: func(ctx context.Context, c *Client) (any, error) { return %s.%s(ctx%s) }},\n",
		e.Method, ep, call, probedKey, chain, name, arg)
}

/* ---------------------------------------------------------------- params -- */

type field struct {
	goName, goType, kind, doc string
	param                     Param
	optional                  bool
}

func paramDoc(p Param) string {
	parts := []string{}
	if p.Description != "" {
		parts = append(parts, p.Description)
	}
	if p.MaxLength > 0 {
		parts = append(parts, fmt.Sprintf("Max length: %d.", p.MaxLength))
	}
	if p.Default != "" {
		parts = append(parts, fmt.Sprintf("Defaults to %s.", p.Default))
	}
	if p.Required {
		parts = append(parts, "Mandatory.")
	}
	return strings.Join(parts, " ")
}

// paramType maps a documented param to a Go type and the form method that
// writes it.
func (g *generator) paramType(n *node, method string, e Endpoint, p Param, parents []string) (string, string) {
	path := strings.Join(append(append([]string{}, parents...), p.Name), ".")
	if t, _, ok := findOverride(e.Path, path); ok {
		return t, "json"
	}
	tn := typeName(n.segs)
	switch p.Type {
	case "NUMBER":
		switch {
		case idLike(p.Name) || strings.HasPrefix(p.Description, "The ID of"):
			return "int64", "id"
		case intLike(p.Name):
			return "int", "int"
		}
		return "float64", "num"
	case "BOOLEAN":
		return "bool", "bool"
	case "DATE":
		return "Date", "date"
	case "CSV":
		if idLike(p.Name) {
			return "[]int64", "ids"
		}
		return "[]string", "strs"
	case "JSON":
		if len(parents) == 0 && p.Name == "filter" && isFilter(p) {
			return "[]Filter", "json"
		}
		if len(p.Fields) == 0 {
			return "any", "json"
		}
		st := g.paramStruct(n, method, e, p, parents)
		if p.IsArray {
			return "[]" + st, "json"
		}
		return st, "json"
	}
	// TEXT, HTML, XML
	if len(p.Enum) > 0 {
		if p.Name == "dir" && strings.Join(p.Enum, ",") == "ASC,DESC" {
			return "SortDir", "enum"
		}
		mid := ""
		for _, par := range parents {
			mid += goName(singular(par))
		}
		base := tn + mid + goName(p.Name)
		withMethod := tn + method + mid + goName(p.Name)
		doc := fmt.Sprintf("a value of the %s parameter of /api/v1/%s/.", path, strings.Join(n.segs, "/"))
		return g.enum(p.Enum, doc, base, withMethod), "enum"
	}
	return "string", "str"
}

// intLike reports whether a NUMBER parameter counts something: rows, days,
// digits, a sequence's counter.
func intLike(name string) bool {
	return name == "limit" || name == "start" || name == "pos" || strings.HasSuffix(name, "Days") ||
		strings.HasPrefix(name, "days") || strings.HasSuffix(strings.ToLower(name), "dayofmonth") ||
		strings.HasSuffix(name, "Digits") || (strings.HasPrefix(name, "current") && strings.HasSuffix(name, "Number"))
}

func isFilter(p Param) bool {
	names := []string{}
	for _, f := range p.Fields {
		names = append(names, f.Name)
	}
	sort.Strings(names)
	return strings.Join(names, ",") == "comparison,field,value"
}

func (g *generator) fields(n *node, method string, e Endpoint, params []Param, parents []string) []field {
	var out []field
	seen := map[string]int{}
	for _, p := range params {
		t, kind := g.paramType(n, method, e, p, parents)
		name := goName(p.Name)
		if seen[name]++; seen[name] > 1 {
			name += strconv.Itoa(seen[name])
		}
		f := field{goName: name, goType: t, kind: kind, doc: paramDoc(p), param: p, optional: !p.Required}
		if f.optional && pointerKind(kind, t) {
			f.goType = "*" + t
		}
		if kind == "json" && f.optional && !strings.HasPrefix(t, "[]") && t != "any" && !pointerKind(kind, t) {
			f.goType = "*" + t
		}
		out = append(out, f)
	}
	return out
}

func pointerKind(kind, t string) bool {
	switch kind {
	case "str", "enum", "int", "id", "num", "bool", "date":
		return true
	case "json":
		return t == "int64" || t == "float64" || t == "string" || t == "bool"
	}
	return false
}

// paramStruct declares the struct of a JSON param and returns its name.
func (g *generator) paramStruct(n *node, method string, e Endpoint, p Param, parents []string) string {
	tn := typeName(n.segs)
	mid := ""
	for _, par := range parents {
		mid += goName(singular(par))
	}
	stem := mid + goName(singular(p.Name))
	fs := g.fields(n, method, e, p.Fields, append(append([]string{}, parents...), p.Name))
	var body strings.Builder
	for _, f := range fs {
		body.WriteString(comment(f.doc, "\t"))
		tag := f.param.Name
		if f.optional {
			tag += ",omitempty"
		}
		fmt.Fprintf(&body, "\t%s %s `json:%q`\n", f.goName, f.goType, tag)
	}
	for _, name := range []string{tn + stem + "Param", tn + method + stem + "Param"} {
		if prev, ok := g.claimed[name]; ok {
			if prev == body.String() {
				return name
			}
			continue
		}
		g.claimed[name] = body.String()
		g.stats.Structs++
		out := g.group(n.segs[0])
		desc := fmt.Sprintf("%s is one entry of the %s parameter of /api/v1/%s, sent as JSON.", name,
			strings.Join(append(append([]string{}, parents...), p.Name), "."), strings.TrimPrefix(e.Path, "/api/v1/"))
		if !p.IsArray {
			desc = fmt.Sprintf("%s is the %s parameter of /api/v1/%s, sent as JSON.", name,
				strings.Join(append(append([]string{}, parents...), p.Name), "."), strings.TrimPrefix(e.Path, "/api/v1/"))
		}
		out.params.WriteString(comment(desc, ""))
		fmt.Fprintf(&out.params, "type %s struct {\n%s}\n\n", name, body.String())
		return name
	}
	panic("no name for param struct " + tn + stem)
}

func (g *generator) emitParams(out *groupOut, n *node, method, name string, e Endpoint) {
	fs := g.fields(n, method, e, e.Params, nil)
	fmt.Fprintf(&out.params, "// %s are the parameters of %s /api/v1/%s.\ntype %s struct {\n", name, e.Method,
		strings.TrimPrefix(e.Path, "/api/v1/"), name)
	for _, f := range fs {
		out.params.WriteString(comment(f.doc, "\t"))
		fmt.Fprintf(&out.params, "\t%s %s\n", f.goName, f.goType)
	}
	out.params.WriteString("}\n\n")
	fmt.Fprintf(&out.params, "func (p *%s) values() (url.Values, error) {\n\tf := newForm()\n\tif p == nil {\n\t\treturn f.done()\n\t}\n", name)
	for _, f := range fs {
		k := f.param.Name
		val := "p." + f.goName
		deref := val
		if strings.HasPrefix(f.goType, "*") && f.kind != "json" {
			deref = "*" + val
		}
		var stmt string
		switch f.kind {
		case "str":
			stmt = fmt.Sprintf("f.str(%q, %s)", k, deref)
		case "enum":
			stmt = fmt.Sprintf("f.str(%q, string(%s))", k, deref)
		case "int":
			stmt = fmt.Sprintf("f.int(%q, %s)", k, deref)
		case "id":
			stmt = fmt.Sprintf("f.id(%q, %s)", k, deref)
		case "num":
			stmt = fmt.Sprintf("f.num(%q, %s)", k, deref)
		case "bool":
			stmt = fmt.Sprintf("f.bool(%q, %s)", k, deref)
		case "date":
			stmt = fmt.Sprintf("f.date(%q, %s)", k, deref)
		case "ids":
			stmt = fmt.Sprintf("f.ids(%q, %s)", k, val)
		case "strs":
			stmt = fmt.Sprintf("f.strs(%q, %s)", k, val)
		case "json":
			stmt = fmt.Sprintf("f.json(%q, %s)", k, val)
		}
		if f.optional {
			fmt.Fprintf(&out.params, "\tif %s != nil {\n\t\t%s\n\t}\n", val, stmt)
		} else {
			fmt.Fprintf(&out.params, "\t%s\n", stmt)
		}
	}
	out.params.WriteString("\treturn f.done()\n}\n\n")
}

